// Run after `npm run build`. Use verified official binaries to avoid Xcode's
// dependency downloader hanging on networks where curl works normally.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

process.chdir(path.dirname(fileURLToPath(import.meta.url)));
execFileSync('npx', ['cap', 'sync', 'ios'], { stdio: 'inherit' });
const version = JSON.parse(fs.readFileSync('node_modules/@capacitor/ios/package.json')).version;
if (version !== '7.6.7') throw new Error('Review binary checksums before upgrading Capacitor.');
const frameworks = 'ios/App/CapApp-SPM/Frameworks';
fs.mkdirSync(frameworks, { recursive: true });
fs.mkdirSync('../产出/Dependencies', { recursive: true });
const hashes = {
  Capacitor: '31f0456603ddc775fe2f3df8dc65b58fb0bb79dca9f7650791c829ce2fee33ff',
  Cordova: '1452a74ca23d2fc670a881705bf3b56491e9ec31271fefe129ca6f602c32e675',
};
for (const [name, checksum] of Object.entries(hashes)) {
  const archive = `../产出/Dependencies/${name}.xcframework.zip`;
  if (!fs.existsSync(archive)) {
    execFileSync('curl', ['-fL', '--retry', '2', '--max-time', '90', '-o', archive,
      `https://github.com/ionic-team/capacitor-swift-pm/releases/download/${version}/${name}.xcframework.zip`], { stdio: 'inherit' });
  }
  const actual = crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
  if (actual !== checksum) throw new Error(`Checksum mismatch: ${archive}`);
  execFileSync('unzip', ['-oq', archive, '-d', frameworks]);
}
fs.writeFileSync('ios/App/CapApp-SPM/Package.swift', `// swift-tools-version: 5.9
// Generated by prepare-ios.mjs using checksum-verified Capacitor ${version} binaries.
import PackageDescription
let package = Package(
    name: "CapApp-SPM",
    platforms: [.iOS(.v15)],
    products: [.library(name: "CapApp-SPM", targets: ["CapApp-SPM"])],
    targets: [
        .binaryTarget(name: "Capacitor", path: "Frameworks/Capacitor.xcframework"),
        .binaryTarget(name: "Cordova", path: "Frameworks/Cordova.xcframework"),
        .target(name: "CapApp-SPM", dependencies: ["Capacitor", "Cordova"])
    ]
)
`);
// App Store forbids even an opaque PNG if it contains an alpha channel.
// Convert the repository's matching JPEG icon to an RGB PNG without alpha.
execFileSync('sips', ['-s', 'format', 'png', '../icon/1024.jpg', '--out',
  'ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png']);
// Preserve upstream line endings when refreshing the browser runtime.
const runtime = 'public/lib/dragonBones.js';
fs.writeFileSync(runtime, fs.readFileSync(runtime, 'utf8').replace(/\r\n/g, '\n'));
console.log('iOS dependencies verified and prepared.');
